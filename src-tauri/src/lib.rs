//! Оболочка Tauri приложения My Personal Tutor: команды, состояние, capabilities.
//!
//! Команды тонкие (5–30 строк): состояние → сервис → DTO. Логика — в `mpt-core` и сервисных
//! крейтах (`docs/01_ARCHITECTURE.md` §2).

/// Версии крейтов приложения: `(имя крейта, версия)`.
///
/// Пригодится экрану «О программе» и диагностике; заодно фиксирует связь `mpt-app` с сервисными
/// крейтами, которые начнут использоваться командами в следующих задачах.
pub const CRATE_VERSIONS: [(&str, &str); 4] = [
    ("mpt-app", env!("CARGO_PKG_VERSION")),
    ("mpt-storage", mpt_storage::VERSION),
    ("mpt-importer", mpt_importer::VERSION),
    ("mpt-services", mpt_services::VERSION),
];

pub mod commands;
pub mod error;
#[cfg(feature = "spikes")]
pub mod spikes;

pub use error::{AppError, AppErrorCode};

/// Путь к сгенерированным TS-привязкам относительно корня репозитория (ADR-23).
pub const BINDINGS_PATH: &str = "src/lib/ipc/bindings.ts";

/// Путь к TS-привязкам спайк-команд (feature `spikes`, T-004.1) относительно корня репозитория.
///
/// Пишется вторым запуском `gen_bindings` с `--features spikes`; `bindings.ts` при этом не
/// трогается, поэтому в нём `spike_*` нет никогда. Импортируется только `src/lib/ipc/spikes.ts`.
pub const SPIKE_BINDINGS_PATH: &str = "src/lib/ipc/bindings.spikes.ts";

/// Заголовок `bindings.ts`, дописывается перед заголовком `tauri-specta`.
const BINDINGS_HEADER: &str =
    "// Generated by `just gen` (src-tauri/src/bin/gen_bindings.rs). Do not edit.";

/// Заголовок `bindings.spikes.ts`.
#[cfg(feature = "spikes")]
const SPIKE_BINDINGS_HEADER: &str = "// Generated by `just gen` (src-tauri/src/bin/gen_bindings.rs, \
     --features spikes). Do not edit.\n// Spike commands (T-004), absent from release builds.";

/// Строитель IPC-контракта: все команды и типы (ADR-23).
///
/// Один и тот же builder регистрирует команды в [`run`] и экспортирует `bindings.ts` в бинаре
/// `gen_bindings`, поэтому привязки не могут разойтись с реальным `invoke_handler`.
/// Ошибки команд в TS — `{ status: "ok", data } | { status: "error", error: AppError }`.
///
/// С feature `spikes` включает и спайк-команды (`commands::collect`).
#[must_use]
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    configure(tauri_specta::Builder::<tauri::Wry>::new().commands(commands::collect()))
}

/// Общие настройки builder'ов: режим ошибок и serde-фазы.
fn configure(builder: tauri_specta::Builder<tauri::Wry>) -> tauri_specta::Builder<tauri::Wry> {
    builder
        .error_handling(tauri_specta::ErrorHandlingMode::Result)
        // Один TS-тип на Rust-тип, без пар `X_Serialize`/`X_Deserialize` (`01_ARCHITECTURE.md` §4).
        .disable_serde_phases()
}

/// Builder только со спайк-командами — для экспорта `bindings.spikes.ts`.
///
/// Команды регистрирует [`specta_builder`] (тот же набор функций), этот builder в
/// `invoke_handler` не используется.
#[cfg(feature = "spikes")]
#[must_use]
pub fn spike_specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    configure(tauri_specta::Builder::<tauri::Wry>::new().commands(commands::collect_spikes()))
}

/// Экспортирует TS-привязки builder'а в файл `path`.
///
/// # Errors
///
/// Ошибка экспорта specta (например, неаннотированный `i64` в DTO) или записи файла.
pub fn export_bindings(path: &std::path::Path) -> Result<(), specta_typescript::Error> {
    specta_builder().export(
        specta_typescript::Typescript::default().header(BINDINGS_HEADER),
        path,
    )
}

/// Экспортирует TS-привязки спайк-команд в файл `path`.
///
/// # Errors
///
/// Как у [`export_bindings`].
#[cfg(feature = "spikes")]
pub fn export_spike_bindings(path: &std::path::Path) -> Result<(), specta_typescript::Error> {
    spike_specta_builder().export(
        specta_typescript::Typescript::default().header(SPIKE_BINDINGS_HEADER),
        path,
    )
}

/// Контекст приложения: `tauri.conf.json`, встроенные ассеты фронтенда, capabilities.
fn context() -> tauri::Context<tauri::Wry> {
    tauri::generate_context!()
}

/// Запускает приложение и блокирует поток до его завершения.
///
/// Мобильная точка входа (`tauri::mobile_entry_point`) появится в Фазе 8.
///
/// # Errors
///
/// Возвращает ошибку Tauri, если не удалось создать окно или event loop.
pub fn run() -> tauri::Result<()> {
    let builder = specta_builder();
    let app = tauri::Builder::default();
    #[cfg(feature = "spikes")]
    let app = app.manage(commands::spike::SpikeTts::default());
    app.invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            Ok(())
        })
        .run(context())
}

#[cfg(test)]
mod tests {
    use super::*;
    use tauri::utils::config::{Csp, FsScope};

    /// CSP из `docs/01_ARCHITECTURE.md` §4a, одной строкой.
    const EXPECTED_CSP: &str = "default-src 'self'; script-src 'self'; \
        style-src 'self' 'unsafe-inline'; \
        img-src 'self' asset: http://asset.localhost data: blob:; \
        media-src 'self' asset: http://asset.localhost blob:; font-src 'self' data:; \
        connect-src ipc: http://ipc.localhost; object-src 'none'; frame-src 'none'";

    #[test]
    fn identifier_matches_adr_24() {
        assert_eq!(context().config().identifier, "dev.rnd-center.mpt");
    }

    #[test]
    fn csp_matches_architecture_and_forbids_eval() {
        let context = context();
        let csp = context.config().app.security.csp.as_ref();
        assert!(
            matches!(csp, Some(Csp::Policy(_))),
            "CSP must be a single policy string"
        );
        let actual = csp.map(ToString::to_string).unwrap_or_default();
        assert_eq!(actual, EXPECTED_CSP);
        assert!(!actual.contains("unsafe-eval"));
    }

    /// `assetProtocol.enable` в `generate_context!` не попадает: протокол включает cargo-фича
    /// `protocol-asset`, а её соответствие конфигу проверяет `tauri_build::build()` при сборке.
    #[test]
    fn asset_protocol_is_limited_to_courses_dir() {
        let context = context();
        let asset = &context.config().app.security.asset_protocol;
        let FsScope::AllowedPaths(paths) = &asset.scope else {
            unreachable!("asset scope must be a plain list: {:?}", asset.scope);
        };
        let paths: Vec<_> = paths.iter().map(|p| p.to_string_lossy()).collect();
        assert_eq!(paths, ["$APPDATA/courses/**"]);
    }

    #[test]
    fn capabilities_grant_no_fs_or_shell_plugins() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("capabilities");
        let mut checked = 0;
        for entry in std::fs::read_dir(&dir).unwrap() {
            let path = entry.unwrap().path();
            let text = std::fs::read_to_string(&path).unwrap();
            for forbidden in ["fs:", "shell:"] {
                assert!(
                    !text.contains(forbidden),
                    "{forbidden} in {path:?} (ADR-11)"
                );
            }
            checked += 1;
        }
        assert!(checked > 0, "no capability files in {dir:?}");
        // Capabilities можно объявить и inline в tauri.conf.json — там их быть не должно.
        assert!(
            context().config().app.security.capabilities.is_empty(),
            "inline capabilities in tauri.conf.json are not allowed"
        );
        let default = std::fs::read_to_string(dir.join("default.json")).unwrap();
        assert!(default.contains("\"core:default\""));
    }

    /// Лицензия фронтенда (`package.json`) и бандла совпадает с лицензией workspace (ADR-24).
    #[test]
    fn package_json_and_bundle_declare_gpl_license() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let package_json = std::fs::read_to_string(root.join("package.json")).unwrap();
        assert!(
            package_json.contains(r#""license": "GPL-3.0-or-later""#),
            "package.json must declare GPL-3.0-or-later"
        );
        assert_eq!(env!("CARGO_PKG_LICENSE"), "GPL-3.0-or-later");
        assert_eq!(
            context().config().bundle.license.as_deref(),
            Some("GPL-3.0-or-later")
        );
    }

    #[test]
    fn bindings_export_succeeds_and_contains_contract() {
        let path = std::env::temp_dir().join(format!("mpt-bindings-{}.ts", std::process::id()));
        export_bindings(&path).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let _ = std::fs::remove_file(&path);
        assert!(text.starts_with(BINDINGS_HEADER), "{text}");
        for needle in [
            "export const commands",
            "appPing",
            "appInfo",
            "export type AppError",
            "\"app.internal\"",
            "\"app.invalid_argument\"",
            "builtAtMs: number",
        ] {
            assert!(
                text.contains(needle),
                "missing {needle:?} in bindings:\n{text}"
            );
        }
        assert!(!text.contains("bigint"), "{text}");
    }

    fn read_repo_file(relative: &str) -> String {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join(relative);
        std::fs::read_to_string(&path)
            .map_err(|e| format!("{path:?}: {e}"))
            .unwrap()
    }

    /// Приёмка T-004.1: в основных привязках (релизная сборка без `spikes`) нет `spike_*`.
    #[test]
    fn committed_bindings_have_no_spike_commands() {
        let text = read_repo_file(BINDINGS_PATH).to_ascii_lowercase();
        assert!(!text.contains("spike"), "spike in {BINDINGS_PATH}");
    }

    #[test]
    fn committed_spike_bindings_have_only_spike_commands() {
        let text = read_repo_file(SPIKE_BINDINGS_PATH);
        for needle in [
            "spikePrepareMedia",
            "spikeTtsVoices",
            "spikeTtsSpeak",
            "\"spike_tts_speak\"",
            "export type AppError",
        ] {
            assert!(text.contains(needle), "missing {needle:?}:\n{text}");
        }
        assert!(!text.contains("appPing"), "{text}");
    }

    #[cfg(not(feature = "spikes"))]
    #[test]
    fn bindings_without_spikes_feature_have_no_spike_commands() {
        let path =
            std::env::temp_dir().join(format!("mpt-bindings-nospike-{}.ts", std::process::id()));
        export_bindings(&path).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let _ = std::fs::remove_file(&path);
        assert!(!text.to_ascii_lowercase().contains("spike"), "{text}");
    }

    /// С `spikes` спайк-команды регистрируются в `invoke_handler` вместе с основными.
    #[cfg(feature = "spikes")]
    #[test]
    fn builder_with_spikes_feature_registers_app_and_spike_commands() {
        let path =
            std::env::temp_dir().join(format!("mpt-bindings-spike-{}.ts", std::process::id()));
        export_bindings(&path).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let _ = std::fs::remove_file(&path);
        for needle in [
            "appPing",
            "appInfo",
            "spikePrepareMedia",
            "spikeTtsVoices",
            "spikeTtsSpeak",
        ] {
            assert!(text.contains(needle), "missing {needle:?}");
        }
    }

    /// Закоммиченный `bindings.spikes.ts` совпадает с тем, что экспортирует builder.
    #[cfg(feature = "spikes")]
    #[test]
    fn spike_bindings_export_matches_committed_file() {
        let path =
            std::env::temp_dir().join(format!("mpt-spike-bindings-{}.ts", std::process::id()));
        export_spike_bindings(&path).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let _ = std::fs::remove_file(&path);
        assert!(text.starts_with(SPIKE_BINDINGS_HEADER), "{text}");
        assert!(
            text == read_repo_file(SPIKE_BINDINGS_PATH),
            "{SPIKE_BINDINGS_PATH} is stale: run `just gen`"
        );
    }

    #[test]
    fn crate_versions_follow_the_workspace_version() {
        for (name, version) in CRATE_VERSIONS {
            assert_eq!(version, env!("CARGO_PKG_VERSION"), "{name}");
        }
    }
}
